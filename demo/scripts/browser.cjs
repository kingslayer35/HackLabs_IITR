/* Browser acceptance against the real local demo. Synthetic sample inputs only. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const AxeBuilder = require('@axe-core/playwright').default;
const base = process.env.TERMMAP_DEMO_URL || 'http://127.0.0.1:8787';
const evidence = path.resolve(__dirname, '../evidence');
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));

(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage(); const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const checks = [];
  try {
    await page.goto(base); await page.waitForFunction(() => !document.getElementById('sample-button').disabled);
    assert.equal(await page.title(), 'TermMap · Clinical term mapping');
    await page.getByLabel('Choose a CSV file').setInputFiles({ name: 'invalid.csv', mimeType: 'text/csv', buffer: Buffer.from('wrong_column\nterm\n') });
    await page.getByRole('alert').waitFor({ state: 'visible' });
    assert.match(await page.getByRole('alert').innerText(), /clinical_entity/);
    assert.equal(await page.getByRole('button', { name: 'Run mapping' }).isDisabled(), true);
    checks.push('Server CSV validation and disabled invalid-run submission');
    await page.route('**/api/health', route => route.fulfill({ json: { worker: { status: 'offline' } } }));
    await page.getByRole('button', { name: 'Use sample CSV' }).click();
    await page.waitForFunction(() => document.getElementById('file-name').textContent === 'termmap_sample.csv');
    await page.getByText('Inference offline', { exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Run mapping' }).isDisabled(), true);
    checks.push('Offline worker keeps uploaded file and blocks inference');
    await page.screenshot({ path: path.join(evidence, 'desktop-upload.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: path.join(evidence, 'mobile-upload.png'), fullPage: true });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    assert.equal(await page.locator('.spinner').evaluate(el => getComputedStyle(el).animationName), 'none');
    await page.emulateMedia({ reducedMotion: 'no-preference' });
    checks.push('390px reflow and reduced motion');
    await page.setViewportSize({ width: 1440, height: 1000 });
    const a11y = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
    fs.writeFileSync(path.join(evidence, 'accessibility.json'), JSON.stringify(a11y, null, 2));
    assert.deepEqual(a11y.violations.map(v => v.id), []);
    checks.push('axe WCAG A/AA scan, uploaded state');
    await page.unroute('**/api/health');
    console.log('UI states passed; waiting for real F11 worker.');
    const deadline = Date.now() + 300000;
    while (Date.now() < deadline) {
      const health = await (await page.request.get(base + '/api/health')).json();
      if (health.worker.status === 'failed') throw new Error(health.worker.message);
      if (['ready', 'busy'].includes(health.worker.status)) break;
      await wait(2000);
    }
    await page.getByRole('button', { name: 'Run mapping' }).waitFor();
    await page.waitForFunction(() => !document.getElementById('run-button').disabled, null, { timeout: 15000 });
    await page.getByRole('button', { name: 'Run mapping' }).click();
    await page.waitForFunction(() => !document.getElementById('download-link').hidden || (!document.getElementById('run-status').hidden && document.getElementById('run-status-text').textContent.includes('could not finish')), null, { timeout: 240000 });
    assert.equal(await page.locator('#error-message').isVisible(), false, await page.locator('#error-message').innerText());
    assert.equal(await page.locator('.term-name').count(), 4);
    assert.match(await page.locator('#validation-text').innerText(), /validation passed/);
    const download = await page.request.get(base + await page.locator('#download-link').getAttribute('href'));
    assert.equal(download.status(), 200); const csv = await download.text();
    assert.equal(csv.trim().split('\n').length, 5);
    assert.match(csv, /^chunk_id,clinical_entity,icd10cm_code,snomed_code/);
    const resultId = await page.evaluate(() => sessionStorage.getItem('termmap-run'));
    const real = await (await page.request.get(base + `/api/jobs/${resultId}/results`)).json();
    assert.equal(real.validator, 'passed'); assert.equal(real.flow, 'F11');
    fs.writeFileSync(path.join(evidence, 'live-sample-results.json'), JSON.stringify(real, null, 2));
    checks.push('Real released F11 inference, four rows, validated code output and CSV download');
    const chooserPromise = page.waitForEvent('filechooser');
    await page.getByRole('button', { name: 'Change file' }).click();
    const chooser = await chooserPromise; await chooser.setFiles([]);
    assert.equal(await page.evaluate(() => sessionStorage.getItem('termmap-run')), resultId);
    checks.push('Changing-file cancellation preserves the completed run');
    await page.locator('summary').filter({ hasText: 'Context & alternatives' }).first().focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('.row-details').first().getAttribute('open'), '');
    await page.screenshot({ path: path.join(evidence, 'desktop-results.png'), fullPage: true });
    const resultsA11y = await new AxeBuilder({ page }).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
    assert.deepEqual(resultsA11y.violations.map(v => v.id), []);
    await page.reload();
    await page.waitForFunction(() => !document.getElementById('download-link').hidden);
    checks.push('Keyboard disclosure, accessible results, refresh recovery');
    await page.route(`**/api/jobs/${resultId}/results`, route => route.fulfill({ json: { ...real, rows: [...real.rows, ...real.rows, ...real.rows] } }));
    await page.reload(); await page.waitForFunction(() => document.getElementById('result-count').textContent === '12');
    assert.equal(await page.locator('.term-name').count(), 10);
    await page.getByRole('button', { name: 'Next results page' }).click();
    assert.equal(await page.locator('.term-name').count(), 2);
    assert.match(await page.locator('#page-range').innerText(), /11–12 of 12/);
    await page.getByRole('button', { name: 'Previous results page' }).click();
    assert.equal(await page.locator('.term-name').count(), 10);
    await page.unroute(`**/api/jobs/${resultId}/results`);
    checks.push('10-row pagination using a browser-only expanded real-result fixture');
    await page.getByRole('button', { name: 'Use sample CSV' }).click();
    await page.waitForFunction(() => !document.getElementById('run-button').disabled);
    await page.getByRole('button', { name: 'Run mapping' }).click();
    await page.getByRole('button', { name: 'Cancel run', exact: true }).click();
    await page.waitForFunction(() => document.getElementById('run-status-text').textContent === 'Run cancelled', null, { timeout: 30000 });
    const cancelledId = await page.evaluate(() => sessionStorage.getItem('termmap-run'));
    assert.equal((await page.request.get(base + `/api/jobs/${cancelledId}/download`)).status(), 409);
    checks.push('Browser cancellation with no incomplete-result download');
    await page.evaluate(id => sessionStorage.setItem('termmap-run', id), resultId);
    await page.reload(); await page.waitForFunction(() => !document.getElementById('download-link').hidden);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.ok(await page.locator('.table-scroll').evaluate(el => el.scrollWidth > el.clientWidth));
    await page.screenshot({ path: path.join(evidence, 'mobile-results.png'), fullPage: true });
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(evidence, 'browser-checks.json'), JSON.stringify({ passed: true, checks, consoleErrors: errors, sampleJob: resultId }, null, 2));
    console.log(JSON.stringify({ passed: true, checks, sampleJob: resultId }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
